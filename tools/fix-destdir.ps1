param([Parameter(Mandatory = $true)][string]$MakefilePath)
$ErrorActionPreference = 'Stop'
$projectRoot = [IO.Path]::GetFullPath((Join-Path $PSScriptRoot '..'))
$generatedFile = (Resolve-Path -LiteralPath $MakefilePath).Path
$allowedFiles = @('arm\o.le-v7-g\Makefile', 'arm\o.le-v7\Makefile',
    'arm-p\o.le-v7-g\Makefile', 'x86\o-g\Makefile')
$allowed = $false
foreach ($relativeFile in $allowedFiles) {
    if ($generatedFile -eq (Join-Path $projectRoot $relativeFile)) { $allowed = $true }
}
if (-not $allowed) { throw 'Expected a generated Makefile inside this project.' }
$content = [IO.File]::ReadAllText($generatedFile)
if ($content -notmatch 'Generated by qmake') { throw 'Refusing to modify a non-qmake Makefile.' }
$variant = Split-Path -Leaf (Split-Path -Parent $generatedFile)
# qmake's Cascades output paths are relative to the project root, but make runs
# inside the variant directory. Remove that extra prefix from ALL generated
# output references (target, objects, moc sources, include paths and rules).
# Release uses qmake's library template: it links in the current directory and
# then deletes the destination before moving the library there. Once both are
# the same directory those relocation commands would delete the linked file.
$relocationPrefix = [regex]::Escape($variant + '/')
$patched = [regex]::Replace($content,
    '(?m)^\t-\$\(DEL_FILE\) ' + $relocationPrefix + '\$\(TARGET[012]?\)[ \t]*\r?\n', '')
$patched = [regex]::Replace($patched,
    '(?m)^\t-\$\(MOVE\) \$\(TARGET\) \$\(TARGET0\) \$\(TARGET1\) \$\(TARGET2\) ' + $relocationPrefix + '[ \t]*\r?\n', '')
# Keep a valid directory operand for mkdir/test and retain relative paths.
$patched = $patched.Replace($variant + '/', './')
if ($patched -ne $content) {
    [IO.File]::WriteAllText($generatedFile, $patched, (New-Object Text.UTF8Encoding($false)))
}
# qmake created moc/object directories at the original nested paths. Prepare
# the normalized paths before a parallel first build starts generating files.
$outputDirectory = Split-Path -Parent $generatedFile
foreach ($outputName in @('.obj', '.moc', '.rcc')) {
    [IO.Directory]::CreateDirectory((Join-Path $outputDirectory $outputName)) | Out-Null
}
Write-Output "Output paths normalized: $MakefilePath"
